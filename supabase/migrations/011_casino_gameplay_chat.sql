  for select using (moderation_status = 'approved');

-- The public live feed needs active-round metadata, but it must never expose the
-- revealed random bytes that would let a client calculate unrevealed playback.
create or replace view public.casino_public_rounds as
select
  round_id,
  round_sequence,
  game,
  status,
  eligible_count,
  started_at,
  playback_started_at,
  playback_ends_at,
  results_hash,
  randomness_provider,
  randomness_account,
  randomness_commit_tx_sig,
  randomness_reveal_tx_sig,
  randomness_verified_at,
  settlement_tx_sig,
  settled_at
from public.casino_rounds;

-- Reveal exactly one in-progress play. Later outcomes remain inaccessible until
-- their own playback window begins.
create or replace view public.casino_public_current_play as
select
  result.round_id,
  result.wallet,
  result.sequence_index,
  result.game,
  result.score,
  result.tie_break,
  result.summary,
  result.outcome,
  result.result_hash,
  result.scheduled_at
from public.casino_game_results result
where result.sequence_index = (
  select min(candidate.sequence_index)
  from public.casino_game_results candidate
  where candidate.round_id = result.round_id
    and candidate.scheduled_at > now()
);

revoke all on public.casino_public_rounds from public;
revoke all on public.casino_public_current_play from public;
grant select on public.casino_public_rounds to anon, authenticated, service_role;
grant select on public.casino_public_current_play to anon, authenticated, service_role;
